def posix(path: str) -> str:
    """Путь в индексе всегда через «/» — и на Windows, и на macOS."""
    out = str(path).replace("\\", "/")
    while out.startswith("./"):
        out = out[2:]
    return out.lstrip("/")


def language_of(rel: str) -> str:
    name = rel.rsplit("/", 1)[-1]
    low = name.lower()
    if low in NAMES:
        return NAMES[low]
    return LANGS.get(os.path.splitext(low)[1], "")


def is_secret_name(name: str) -> bool:
    """Секретное имя файла — тем же правилом, что у чтения проекта; без импорта тяжёлых модулей."""
    try:
        import request_context as rc  # noqa: PLC0415 — модуль движка лежит рядом со скриптами
        return bool(rc.SECRET_NAME.match(name))
    except Exception:  # noqa: BLE001 — индекс не должен падать из-за старого движка
        return bool(SECRET_NAME_FALLBACK.match(name))


def _has_dir(parts: list) -> str:
    low = [p.lower() for p in parts[:-1]]
    for d in DEPS_DIRS:
        if d in low:
            return d
    return ""


def _in_test_dir(parts: list) -> bool:
    low = [p.lower() for p in parts[:-1]]
    return any(p in TEST_DIRS for p in low)


def _in_migration_dir(parts: list) -> bool:
    low = [p.lower() for p in parts[:-1]]
    joined = "/".join(low)
    return any(d in MIGRATION_DIRS for d in low) or any(joined.endswith("/" + d) for d in MIGRATION_DIRS)


def role_of(rel: str) -> tuple:
    """(роль, почему) — роль файла для индекса и объяснение человеку."""
    parts = posix(rel).split("/")
    name = parts[-1]
    low = name.lower()
    if _has_dir(parts):
        return "vendor", "папка зависимости"
    if _in_test_dir(parts) or TEST_NAME.match(name):
        return "test", "тестовая папка или имя"
    if _in_migration_dir(parts) or MIGRATION_NAME.match(name):
        return "migration", "миграция базы"
    if low in CONFIG_NAMES or os.path.splitext(low)[1] in CONFIG_EXT:
        return "config", "файл настройки"
    if os.path.splitext(low)[1] in DOC_EXT or "docs" in [p.lower() for p in parts[:-1]]:
        return "doc", "документация"
    if GENERATED_NAME.search(name):
        return "generated", "имя сгенерированного файла"
    return "src", "исходный код"


def classify(rel: str, head: bytes | None = None) -> tuple:
    """(пропуск, роль, почему) — почему файл не разбирается, или пустой пропуск.

    `head` — первые килобайты содержимого; без него решают только путь и имя. Двоичное,
    сгенерированное и минифицированное определяется по содержимому, когда оно уже прочитано.
    """
    parts = posix(rel).split("/")
    name = parts[-1]
    low = name.lower()
    role, role_reason = role_of(rel)
    if role == "vendor":
        return "deps", "vendor", role_reason
    if is_secret_name(name):
        return "secret", role, "секретное имя файла"
    if low in LOCK_NAMES or low.endswith(".lock"):
        return "lock", role, "файл блокировки"
    if os.path.splitext(low)[1] in BINARY_EXT:
        return "binary", role, "двоичное расширение"
    if MINIFIED_NAME.search(name):
        return "minified", role, "минифицированное имя"
    if GENERATED_NAME.search(name):
        return "generated", "generated", "имя сгенерированного файла"
    if head is not None:
        if b"\0" in head[:8000]:
            return "binary", role, "нулевые байты"
        if GENERATED_HEAD.search(head[:1024]):
            return "generated", "generated", "заголовок сгенерированного файла"
    return "", role, role_reason


def decode_text(data: bytes) -> tuple:
    """(текст, кодировка) по порядку плана: UTF-8 с BOM, UTF-8, cp1251, latin-1.

    Latin-1 не ошибается никогда, поэтому последний. Двоичное сюда не попадает: его отсекает
    `classify` по NUL или расширению. Ошибки заменяются, чтобы индекс не падал на одном файле.
    """
    if data.startswith(codecs.BOM_UTF8):
        return data.decode("utf-8-sig", "replace"), "utf-8-sig"
    for enc in ("utf-8", "cp1251"):
        try:
            return data.decode(enc), enc
        except UnicodeDecodeError:
            continue
    return data.decode("latin-1", "replace"), "latin-1"


def normalize_newlines(text: str) -> str:
    """Одинаковые концы строк на всех системах: CRLF и CR становятся LF."""
    return text.replace("\r\n", "\n").replace("\r", "\n")


def text_hash(text: str) -> str:
    """Хэш нормализованного текста: CRLF и кодировка не меняют значение."""
    return hashlib.sha256(normalize_newlines(text).encode("utf-8")).hexdigest()


def line_count(text: str) -> int:
    """Число строк после нормализации: пустой файл — 0."""
    if not text:
        return 0
    return normalize_newlines(text).count("\n") + (0 if text.endswith(("\n", "\r")) else 1)


def mask_secret_lines(text: str, hits) -> tuple:
    """(текст с закрытыми строками, находки). Значение секрета не возвращается и не хранится.

    Маска закрывает всю строку, а не только совпадение: иначе рядом с токеном останутся
    соседние значения, которых сканер не знает. Номера строк не меняются.
    """
    lines = normalize_newlines(text).split("\n")
    for _rule, n, _mask in hits:
        if 1 <= int(n) <= len(lines):
            lines[int(n) - 1] = "‹секрет скрыт›"
    return "\n".join(lines), hits


def scan_text(text: str) -> list:
    """Находки секретов в тексте через общий сканер движка; при его отсутствии — пусто."""
    try:
        from aurora_common import scan_secret_text  # noqa: PLC0415
        return scan_secret_text(text)
    except Exception:  # noqa: BLE001 — индекс не должен падать из-за старого движка
        return []


def path_words(rel: str) -> list:
    """Слова пути для поиска: части каталогов и имени, включая CamelCase."""
    words = []
    for part in posix(rel).split("/"):
        part = os.path.splitext(part)[0]
        words.extend(re.findall(r"[A-Za-z_][A-Za-z0-9_]{1,}", part))
        for chunk in re.findall(r"[A-Z]+[a-z0-9]*|[a-z0-9]+", part):
            if len(chunk) > 1:
                words.append(chunk)
    seen = set()
    out = []
    for w in words:
        low = w.lower()
        if low not in seen:
            seen.add(low)
            out.append(low)
    return out


def language_summary(files) -> dict:
    """{язык: {files, lines}} по строкам инвентаря, без пропущенных файлов."""
    out = {}
    for f in files:
        if f.skipped or not f.lang:
            continue
        row = out.setdefault(f.lang, {"files": 0, "lines": 0})
        row["files"] += 1
        row["lines"] += f.lines
    return dict(sorted(out.items(), key=lambda kv: (-kv[1]["lines"], kv[0])))
